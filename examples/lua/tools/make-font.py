# Generates shaders/ui/font.slang: printable ASCII (32..126) as 16 x 32 one-bit glyphs,
# rendered from Cascadia Mono (SIL Open Font License 1.1; it ships with Windows and at
# https://github.com/microsoft/cascadia-code). Needs Pillow.
#
#   python tools/make-font.py [path/to/CascadiaMono.ttf]

import os
import sys

from PIL import Image, ImageDraw, ImageFont

WIDTH, HEIGHT, SIZE = 16, 32, 26
FIRST, LAST = 32, 126

font_path = sys.argv[1] if len(sys.argv) > 1 else "C:/Windows/Fonts/CascadiaMono.ttf"
font = ImageFont.truetype(font_path, SIZE)
ascent, _ = font.getmetrics()

words = []
for code in range(FIRST, LAST + 1):
    image = Image.new("L", (WIDTH, HEIGHT), 0)
    # Centered across the cell; the baseline 2 pixels below the ascent, for the descenders.
    x = (WIDTH - font.getlength(chr(code))) / 2
    ImageDraw.Draw(image).text((x, 1), chr(code), font=font, fill=255)
    rows = []
    for y in range(HEIGHT):
        bits = 0
        for px in range(WIDTH):
            if image.getpixel((px, y)) >= 110:
                bits |= 1 << px
        rows.append(bits)
    # Two rows a word: row 2k in the low half, row 2k + 1 in the high half.
    for k in range(HEIGHT // 2):
        words.append(rows[2 * k] | (rows[2 * k + 1] << 16))

out = os.path.join(os.path.dirname(__file__), "..", "shaders", "ui", "font.slang")
os.makedirs(os.path.dirname(out), exist_ok=True)
with open(out, "w", newline="\n") as f:
    f.write("// Generated by tools/make-font.py: printable ASCII (32..126) as 16 x 32 one-bit\n")
    f.write("// glyphs, from Cascadia Mono (SIL Open Font License 1.1, Microsoft).\n")
    f.write("// Glyph g's row y is bits 0..15 (x) of the half (y & 1) of kFontRows[g * 16 + y / 2].\n\n")
    f.write("static const uint kFontFirst = %d;\n" % FIRST)
    f.write("static const uint kFontLast = %d;\n" % LAST)
    f.write("static const uint2 kFontCell = uint2(%d, %d);\n\n" % (WIDTH, HEIGHT))
    f.write("static const uint kFontRows[%d] = {\n" % len(words))
    for i in range(0, len(words), 8):
        f.write("    " + ", ".join("0x%08xu" % w for w in words[i:i + 8]) + ",\n")
    f.write("};\n")
print("wrote", os.path.normpath(out), len(words), "words")
